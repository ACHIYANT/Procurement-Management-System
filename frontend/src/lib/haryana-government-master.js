const ROOT_ORDER = [
  "Department",
  "Authority",
  "Commission",
  "University",
  "Medical College",
  "Society",
  "Court",
];

const compareByLabel = (left, right) => left.label.localeCompare(right.label);

export const getHaryanaGovernmentMasterOptions = () => {
  const childrenByParent = new Map();

  for (const entry of HARYANA_GOVERNMENT_MASTER) {
    if (!entry.parent) continue;
    if (!childrenByParent.has(entry.parent))
      childrenByParent.set(entry.parent, []);
    childrenByParent.get(entry.parent).push(entry);
  }

  for (const list of childrenByParent.values()) {
    list.sort(compareByLabel);
  }

  const visited = new Set();
  const flattened = [];

  const pushEntry = (entry, depth = 0) => {
    if (!entry || visited.has(entry.value)) return;
    visited.add(entry.value);
    flattened.push({
      label: `${depth > 0 ? `${"  ".repeat(depth)}- ` : ""}${entry.label}`,
      value: entry.label,
      rawValue: entry.value,
      group: entry.group,
      parent: entry.parent,
      depth,
    });

    const children = childrenByParent.get(entry.value) || [];
    for (const child of children) {
      pushEntry(child, depth + 1);
    }
  };

  const rootEntries = HARYANA_GOVERNMENT_MASTER.filter(
    (entry) => !entry.parent,
  ).sort((left, right) => {
    const leftIndex = ROOT_ORDER.indexOf(left.group);
    const rightIndex = ROOT_ORDER.indexOf(right.group);
    if (leftIndex !== rightIndex)
      return (
        (leftIndex === -1 ? 999 : leftIndex) -
        (rightIndex === -1 ? 999 : rightIndex)
      );
    return compareByLabel(left, right);
  });

  for (const entry of rootEntries) {
    pushEntry(entry, 0);
  }

  for (const entry of HARYANA_GOVERNMENT_MASTER) {
    if (!visited.has(entry.value)) {
      pushEntry(entry, 0);
    }
  }

  return flattened;
};

export const getHaryanaGovernmentMasterTree = () => {
  const byValue = new Map(
    HARYANA_GOVERNMENT_MASTER.map((entry) => [
      entry.value,
      { ...entry, children: [] },
    ]),
  );

  for (const entry of byValue.values()) {
    if (entry.parent && byValue.has(entry.parent)) {
      byValue.get(entry.parent).children.push(entry);
    }
  }

  for (const entry of byValue.values()) {
    entry.children.sort(compareByLabel);
  }

  return Array.from(byValue.values())
    .filter((entry) => !entry.parent || !byValue.has(entry.parent))
    .sort((left, right) => {
      const leftIndex = ROOT_ORDER.indexOf(left.group);
      const rightIndex = ROOT_ORDER.indexOf(right.group);
      if (leftIndex !== rightIndex)
        return (
          (leftIndex === -1 ? 999 : leftIndex) -
          (rightIndex === -1 ? 999 : rightIndex)
        );
      return compareByLabel(left, right);
    });
};

export default HARYANA_GOVERNMENT_MASTER;
