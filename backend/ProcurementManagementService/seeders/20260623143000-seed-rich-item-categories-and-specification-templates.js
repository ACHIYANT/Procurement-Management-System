const quote = (name) => `\`${name}\``;

const upsertRow = async (queryInterface, tableName, row, updateColumns) => {
  const columns = Object.keys(row);
  const sql = `
    INSERT INTO ${quote(tableName)} (${columns.map(quote).join(", ")})
    VALUES (${columns.map((column) => `:${column}`).join(", ")})
    ON DUPLICATE KEY UPDATE ${updateColumns
      .map((column) => `${quote(column)} = VALUES(${quote(column)})`)
      .join(", ")}
  `;

  await queryInterface.sequelize.query(sql, { replacements: row });
};

const getCategoryId = async (queryInterface, categoryName) => {
  const [rows] = await queryInterface.sequelize.query(
    `SELECT id FROM ${quote(ITEM_CATEGORY_TABLE)} WHERE category_name = :categoryName LIMIT 1`,
    { replacements: { categoryName } },
  );

  return rows?.[0]?.id;
};

